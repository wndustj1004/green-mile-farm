-- =============================================================
--  그린마일 팜 — 랜딩 소개 섹션 복구 (실수로 삭제한 경우)
--  실행 위치: Supabase 대시보드 > SQL Editor > New query > 붙여넣기 > Run
--  여러 번 다시 실행해도 안전합니다.
--
--  [왜 이 파일이 필요한가]
--  메인페이지의 소개 섹션(G.P.S 소개 / 공모사업 / 대중교통·온실가스 / 작물 사진)은
--  landing_sections 테이블의 "행 순서(위에서 몇 번째인가)"로 어떤 디자인을 보여줄지
--  결정한다(components/LandingSections.tsx). 즉 행이 하나라도 지워지면 아래 섹션들이
--  한 칸씩 밀려 엉뚱하게 보이거나 사라진다.
--
--  [중요] 1~4번째 섹션의 제목·본문은 화면에 나오지 않는다(디자인이 코드에 고정,
--  문구는 site_texts에서 가져옴). 즉 이 행들은 "자리를 잡아주는 자리표"일 뿐이다.
--  실제로 내용이 쓰이는 것은 5번째 '작물 사진 캐러셀'(제목·본문·사진)뿐이다.
-- =============================================================


-- -------------------------------------------------------------
--  STEP 1. 먼저 현재 상태를 확인한다 (이 SELECT만 따로 실행)
--  → 결과가 아래 "정상 상태"와 다르면 STEP 2를 실행한다.
--
--  정상 상태(5행):
--   1 🌱 G.P.S 동아리 소개
--   2 🏆 그린 광주 공모사업
--   3 🚍 친환경 대중교통 정책·현황
--   4 🌍 교통부문 온실가스   (화면에는 안 나오지만 순서 유지를 위해 반드시 있어야 함)
--   5 🥬 작물 사진 캐러셀    (사진 여러 장 첨부됨)
-- -------------------------------------------------------------
select
  sort_order,
  visible,
  emoji,
  title,
  coalesce(array_length(images, 1), 0) as 사진수
from public.landing_sections
order by sort_order;


-- -------------------------------------------------------------
--  STEP 2. 복구 실행
--  5개 행을 올바른 순서로 다시 만든다.
--  작물 사진 캐러셀에 붙어 있던 사진 목록은 자동으로 찾아서 그대로 옮겨준다.
--  (사진 파일 자체는 landing-images 저장소에 그대로 남아 있으므로 지워지지 않는다)
-- -------------------------------------------------------------
do $$
declare
  v_images text[];
  v_title  text;
  v_body   text;
begin
  -- 사진이 붙어 있는 '가장 아래 행' = 작물 사진 캐러셀로 보고 내용을 살려둔다
  select images, title, body
    into v_images, v_title, v_body
    from public.landing_sections
   where coalesce(array_length(images, 1), 0) > 0
   order by sort_order desc
   limit 1;

  -- 캐러셀 행까지 지워졌다면 빈 값으로 시작 (사진은 관리자 화면에서 다시 첨부)
  v_images := coalesce(v_images, '{}');
  v_title  := coalesce(nullif(v_title, ''), 'G.P.S가 직접 키운 작물');
  v_body   := coalesce(v_body, '');

  delete from public.landing_sections;

  insert into public.landing_sections (sort_order, emoji, title, body, visible, images) values
    (1, '🌱', 'G.P.S 동아리 소개',
     '[자리표] 이 행의 제목·본문은 화면에 표시되지 않습니다.
G.P.S 소개 섹션의 실제 문구는 관리자 > 랜딩 내용 > "메인페이지 텍스트"(gps.* 항목)에서 수정하세요.
이 행을 삭제하면 아래 섹션들이 한 칸씩 밀려 메인페이지가 깨집니다.',
     true, '{}'),

    (2, '🏆', '그린 광주 공모사업',
     '[자리표] 이 행의 제목·본문은 화면에 표시되지 않습니다.
공모사업 섹션은 디자인·내용이 코드에 고정되어 있습니다(components/ProjectSection.tsx).
이 행을 삭제하면 아래 섹션들이 한 칸씩 밀려 메인페이지가 깨집니다.',
     true, '{}'),

    (3, '🚍', '친환경 대중교통 정책·현황',
     '[자리표] 이 행의 제목·본문은 화면에 표시되지 않습니다.
대중교통 섹션 + 광주 교통 온실가스 DATA 섹션이 함께 표시됩니다
(components/TransportSection.tsx, EmissionDataSection.tsx).
이 행을 삭제하면 아래 섹션들이 한 칸씩 밀려 메인페이지가 깨집니다.',
     true, '{}'),

    (4, '🌍', '교통부문 온실가스 (화면 미표시 · 순서 유지용)',
     '[자리표 · 반드시 남겨둘 것] 이 행은 화면에 아무것도 표시하지 않습니다.
예전 온실가스 섹션이 위 대중교통 섹션에 통합되면서 빈 자리가 되었지만,
이 행이 없으면 아래 "작물 사진 캐러셀"이 한 칸 위로 올라와 엉뚱한 디자인으로 보입니다.
비어 보인다고 삭제하지 마세요.',
     true, '{}'),

    (5, '🥬', v_title, v_body, true, v_images);
end $$;


-- -------------------------------------------------------------
--  STEP 3. 복구 결과 확인 (5행이 순서대로 나오면 정상)
-- -------------------------------------------------------------
select
  sort_order,
  visible,
  emoji,
  title,
  coalesce(array_length(images, 1), 0) as 사진수
from public.landing_sections
order by sort_order;

