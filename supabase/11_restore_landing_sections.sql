--  1) 메인페이지 새로고침 → G.P.S 소개 / 공모사업 / 대중교통+온실가스 / 작물 사진 순서 확인
--  2) 작물 사진이 비어 있으면 관리자 > 랜딩 내용 > 5번째 섹션에서 사진을 다시 첨부
--     (기존 파일은 landing-images 저장소에 남아 있음)
--
--  앞으로 주의
--  - 관리자 화면에서 섹션을 삭제하거나 순서를 바꾸면 메인페이지가 깨집니다.
--  - 특히 4번째 "교통부문 온실가스" 행은 화면에 안 보여도 지우면 안 됩니다.
-- =============================================================
